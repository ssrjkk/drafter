let currentLocale: Locale = 'en';

function getNestedValue(obj: NestedMessages, path: string): string | undefined {
  let current: Record<string, unknown> = obj as Record<string, unknown>;
  for (const key of path.split('.')) {
    if (typeof current !== 'object' || current === null) return undefined;
    const next = current[key];
    if (next === undefined || next === null) return undefined;
    if (typeof next === 'string') return next;
    if (typeof next === 'object') {
      current = next as Record<string, unknown>;
      continue;
    }
    return undefined;
  }
  return undefined;
}

export function t(key: string, params?: Record<string, string>): string {
  const value = getNestedValue(messages[currentLocale], key)
    ?? getNestedValue(messages.en, key)
    ?? key;
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, name) => params[name] || `{{${name}}}`);
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
  }
}

export function getLocale(): Locale {
  return currentLocale;
}

export function initI18n(): Locale {
  if (typeof window === 'undefined') return 'en';
  let saved: string | null = null;
  try { saved = localStorage.getItem(STORAGE_KEYS.locale); } catch { /* storage unavailable */ }
  if (saved && isValidLocale(saved)) {
    setLocale(saved);
    return saved;
  }
  const browserLang = (navigator.language ?? '').slice(0, 2);
  if (isValidLocale(browserLang)) {
    setLocale(browserLang);
    return browserLang;
  }
  return 'en';
}

export function saveLocale(locale: Locale): void {
  setLocale(locale);
  try { localStorage.setItem(STORAGE_KEYS.locale, locale); } catch { /* storage unavailable */ }
}

function isValidLocale(value: string): value is Locale {
  return value in messages;
}

